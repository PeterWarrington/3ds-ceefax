#!/usr/bin/env python3
"""Generate source/font.h (SAA5050 English G0 set) from Bedstead's bedstead.c.

    curl -O https://bjh21.me.uk/bedstead/bedstead.c
    python3 tools/gen_font.py bedstead.c > source/font.h
"""
import re
import sys

# English national option subset differs from ASCII at these positions.
UK = {
    0x23: 0x00A3,  # pound sign
    0x5B: 0x2190,  # left arrow
    0x5C: 0x00BD,  # one half
    0x5D: 0x2192,  # right arrow
    0x5E: 0x2191,  # up arrow
    0x5F: 0x0023,  # hash
    0x60: 0x2014,  # long dash
    0x7B: 0x00BC,  # one quarter
    0x7C: 0x2016,  # double vertical bar
    0x7D: 0x00BE,  # three quarters
    0x7E: 0x00F7,  # divide
    0x7F: 0x25A0,  # filled block
}

ENTRY = re.compile(r'\{\s*"((?:\\[0-7]{1,3}){9})"\s*,\s*0x([0-9a-fA-F]+)\s*,\s*"([^"]+)"')


def main(path):
    src = open(path, encoding="utf-8").read()
    glyphs = {}
    for m in ENTRY.finditer(src):
        rows = [int(x, 8) for x in re.findall(r"\\([0-7]{1,3})", m.group(1))]
        cp, name = int(m.group(2), 16), m.group(3)
        # SAA5050 apostrophe is straight
        if cp == 0x27 and name != "quotesingle":
            continue
        glyphs.setdefault(cp, rows)

    out = [
        "// Generated by tools/gen_font.py from Bedstead (CC0 public domain),",
        "// a reproduction of the Mullard SAA5050 teletext character set.",
        "// 96 glyphs for codes 0x20-0x7F, 9 rows each, 5 bits per row (bit 4 = left).",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint8_t ttx_font[96][9] = {",
    ]
    for code in range(0x20, 0x80):
        cp = UK.get(code, code)
        rows = glyphs[cp]
        body = ",".join("0x%02x" % r for r in rows)
        label = chr(cp) if cp < 0x7F else "U+%04X" % cp
        out.append("    {%s}, // 0x%02x %s" % (body, code, label))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
